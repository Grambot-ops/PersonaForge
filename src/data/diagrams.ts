export const getDiagram = (projectId: number, isMini?: boolean): DiagramConfig => {
  const config = diagrams[projectId];
  if (!config) return { nodes: [], edges: [] };
  if (!isMini || !config.coreNodeIds) return config;

  const coreNodes = config.nodes.filter(node => 
    config.coreNodeIds!.includes(node.id) || node.type === "customGroup"
  );
  
  // Keep only groups that have at least one active core child node
  const activeNodes = coreNodes.filter(node => {
    if (node.type === "customGroup") {
      return coreNodes.some(child => child.parentId === node.id);
    }
    return true;
  });
  
  const activeNodeIds = activeNodes.map(n => n.id);
  const coreEdges = config.edges.filter(edge => 
    activeNodeIds.includes(edge.source) && activeNodeIds.includes(edge.target)
  );

  return { nodes: activeNodes, edges: coreEdges };
};
